-- Curated from ReplicatedStorage["assets(VFX for use)"]; authored curves are kept
-- where the source emitter had them. The "VFX :D" entries are a texture library
-- whose emitters carry default properties, so only the flipbook is taken and
-- VoidRendVFX supplies the motion. Code-backed so Rojo installs do not depend
-- on the demo packs.
local function seq(...)
	local points = {}
	for _, p in ipairs({...}) do table.insert(points, NumberSequenceKeypoint.new(p[1], p[2], p[3] or 0)) end
	return NumberSequence.new(points)
end
local VIOLET = Color3.new(0.7569, 0.3686, 1)

local function sheet(texture, layout)
	return {
		Texture = texture,
		FlipbookLayout = layout,
		FlipbookMode = if layout == Enum.ParticleFlipbookLayout.None then Enum.ParticleFlipbookMode.Loop else Enum.ParticleFlipbookMode.OneShot,
		FlipbookStartRandom = false,
		LightInfluence = 0,
		Rotation = NumberRange.new(0),
		RotSpeed = NumberRange.new(0),
		Acceleration = Vector3.zero,
		Drag = 0,
		Squash = NumberSequence.new(0),
		ZOffset = 0,
		LockedToPart = false,
	}
end

