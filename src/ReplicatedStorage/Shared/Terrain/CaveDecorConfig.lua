--[[
	CaveDecorConfig

	What grows, hangs and stands in each biome's caves, and how thickly.
	CaveDecor reads this; nothing in here is code.

	A DECORATION IS A BLOCK. It occupies one cell of the block grid on a cave
	floor or ceiling (or a short stack of them), so it is drawn, streamed,
	pooled, mined, remembered and regenerated by exactly the machinery every
	other block uses, and costs one Part.

	===========================================================================
	ARTWORK, AND PLACEHOLDERS
	===========================================================================

	Every decoration is a MagicaVoxel model in assets/voxel-cave-decor (one
	per height it can grow to: Icicle, Icicle2, Icicle3), built into
	ReplicatedStorage.TerrainAssets.Blocks by roblox/BuildCaveDecor.lua. A
	piece several blocks tall is cut into one-block SEGMENTS, each a block of
	its own: Icicle3_1 is the bottom block of a three-block icicle, Icicle3_3
	the top (CaveDecor.segmentName). A one-block piece keeps the plain name.

	A template there is an invisible 4-stud cell Part (attribute CellArt)
	carrying the voxel art as welded children. Where a template is missing
	(the place lost its assets, a new type) the block is drawn as a plain
	4 x 4 x 4 Part in the colour and material its `placeholder` describes.
	Decorations are never merged into runs: every one is its own Part.

	===========================================================================
	TYPE FIELDS
	===========================================================================

	  block         block name, and the name of the Part in the world. Unique.
	  anchor        "floor" (stands on the cave floor) or "ceiling" (hangs).
	  height        {min, max} blocks. A piece taller than 1 is a stack.
	  placeholder   { color, material, transparency? } for the stand-in Part.
	  drop          item granted when mined - must exist in ItemDefinitions -
	                or false for a purely decorative piece, which breaks and
	                gives nothing. A piece with a drop is COLLECTIBLE: once
	                harvested it is remembered (OreDepletion) and does not come
	                back when its chunk regenerates.
	  breakSeconds  time to break with the reference pickaxe.
	  power         pickaxe miningPower needed (default 1).
	  passable      true to let players walk through it (hanging roots, webs).
	                Solid by default.
	  open          floor pieces only. false (the default) keeps the piece
	                against a wall, out of the walking line, unless the cave is
	                at least OpenFloorClearance tall there. true lets it stand
	                anywhere.

	===========================================================================
	BIOME ENTRIES
	===========================================================================

	CaveDecorConfig.Biomes[biomeName] is a list, tried in order for each floor
	and each ceiling cell; the first that rolls in wins that cell. The biome is
	the COLUMN's, so decorations change where the rock does.

	  type           a key of Types.
	  density        chance per suitable cell INSIDE one of this entry's
	                 patches. Outside a patch it is density * SparseFactor.
	  patchBlocks    how big its patches are, in blocks.
	  patchCoverage  what fraction of the underground is a patch for it, 0..1.
	                 Low coverage with high density reads as clusters; high
	                 coverage with low density as an even scatter.
	  minDepth / maxDepth   optional, blocks below the surface.
]]

