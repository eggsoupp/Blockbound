--[[
	Structural sanity check. Runs at init. Item names are checked by the
	caller, which is the side that can see ItemDefinitions.
]]
function CaveDecorConfig.validate()
	local function unit(value, label)
		assert(type(value) == "number" and value >= 0 and value <= 1, label .. " must be in [0, 1]")
	end

	assert(CaveDecorConfig.DensityMultiplier >= 0, "[CaveDecorConfig] DensityMultiplier must not be negative")
	unit(CaveDecorConfig.SparseFactor, "[CaveDecorConfig] SparseFactor")
	assert(CaveDecorConfig.MinHeadroomBlocks >= 2, "[CaveDecorConfig] MinHeadroomBlocks under 2 would block passages")
	assert(CaveDecorConfig.MinClearanceBlocks > CaveDecorConfig.MinHeadroomBlocks,
		"[CaveDecorConfig] MinClearanceBlocks must exceed MinHeadroomBlocks")
	assert(CaveDecorConfig.MaxPerChunk >= 0, "[CaveDecorConfig] MaxPerChunk must not be negative")

	local seenBlock = {}
	for name, def in pairs(CaveDecorConfig.Types) do
		local label = string.format("[CaveDecorConfig] Types.%s", name)
		assert(type(def.block) == "string" and def.block ~= "", label .. " needs a block name")
		assert(not seenBlock[def.block], label .. " reuses block name " .. def.block)
		seenBlock[def.block] = true
		assert(def.anchor == "floor" or def.anchor == "ceiling", label .. ".anchor must be \"floor\" or \"ceiling\"")
		assert(type(def.height) == "table" and def.height.min >= 1 and def.height.max >= def.height.min and def.height.max <= 4,
			label .. ".height needs 1 <= min <= max <= 4")
		assert(type(def.placeholder) == "table" and typeof(def.placeholder.color) == "Color3",
			label .. ".placeholder needs a color")
		assert(def.drop == false or (type(def.drop) == "string" and def.drop ~= ""),
			label .. ".drop must be an item name or false")
		assert(type(def.breakSeconds) == "number" and def.breakSeconds > 0, label .. " needs breakSeconds")
	end

	for biome, entries in pairs(CaveDecorConfig.Biomes) do
		for index, entry in ipairs(entries) do
			local label = string.format("[CaveDecorConfig] Biomes.%s[%d]", biome, index)
			assert(CaveDecorConfig.Types[entry.type], label .. " names an unknown type " .. tostring(entry.type))
			unit(entry.density, label .. ".density")
			unit(entry.patchCoverage, label .. ".patchCoverage")
			assert(type(entry.patchBlocks) == "number" and entry.patchBlocks >= 2, label .. ".patchBlocks must be at least 2")
		end
	end
end

return CaveDecorConfig
