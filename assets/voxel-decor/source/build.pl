#!/usr/bin/perl
# Builds every decor piece in designs/*.pl:
#   ../vox/<Id>.vox             MagicaVoxel model (Body, plus Leaf for a door)
#   ../roblox/data/<Id>.lua     greedy-merged boxes for ../roblox/BuildDecor.lua
#   ../previews/<Id>.png        front 3/4 and back 3/4
#   ../previews/_sheet.png      every piece, front 3/4, in build order
#   src/ReplicatedStorage/Shared/Building/DecorShapes.lua
#                               hinge / seat / flames / glows / rungs / surface
# Usage: perl build.pl [Id ...]   (no ids = everything; the sheet and
#                                   DecorShapes are only written for a full run)
use strict;
use warnings;
use FindBin;
use lib $FindBin::Bin;
use lib "$FindBin::Bin/../../voxel-enemies/source";
use POSIX qw(floor);
use VoxLib;
use VoxOut;
use DecorKit;

my $root = "$FindBin::Bin/..";
my $repo = "$root/../..";
my %want = map { $_ => 1 } @ARGV;
mkdir "$root/$_" for qw(vox roblox roblox/data previews);

DecorKit::load_textures("$repo/assets/item-icons/source/icons.txt");
require "$FindBin::Bin/materials.pl";
for my $file (sort glob("$FindBin::Bin/designs/*.pl")) {
	do $file or die "$file: " . ($@ || $!);
}

my @all = DecorKit::pieces();
my @built = grep { !%want || $want{ $_->{name} } } @all;
die "no pieces match @ARGV\n" unless @built;

# ---------------------------------------------------------------- .vox

sub vchunk { my ($id, $c, $k) = @_; $k //= ''; return $id . pack('VV', length $c, length $k) . $c . $k }
sub vstr { my $s = shift; return pack('V', length $s) . $s }
sub vdict { my %d = @_; my $o = pack('V', scalar keys %d); $o .= vstr($_) . vstr($d{$_}) for sort keys %d; return $o }

# Cell frame (x right, y up, front +Z) -> MagicaVoxel (x, y, z up), front
# facing MagicaVoxel's front (-y). Shifted so every coordinate is >= 0.
sub write_vox {
	my ($m, $path) = @_;
	my $by = VoxOut::parts_of($m);
	my (@shapes, $body);
	$body = '';
	for my $name (@{ $m->{parts} }) {
		my @v = map { [ $_->[0] + 8, 7 - $_->[2], $_->[1], $_->[3] ] } @{ $by->{$name} || [] };
		next unless @v;
		my ($lo, $hi) = VoxOut::bounds(\@v);
		my @size = map { $hi->[$_] - $lo->[$_] + 1 } 0 .. 2;
		my $xyzi = pack('V', scalar @v);
		$xyzi .= pack('CCCC', $_->[0] - $lo->[0], $_->[1] - $lo->[1], $_->[2] - $lo->[2], $_->[3]) for @v;
		$body .= vchunk('SIZE', pack('VVV', @size)) . vchunk('XYZI', $xyzi);
		# Translation is the model's centre, MagicaVoxel-style (floor(size/2)).
		my @t = map { $lo->[$_] + floor($size[$_] / 2) - ($_ == 2 ? 0 : 8) } 0 .. 2;
		push @shapes, [ $name, "@t" ];
	}
	my ($scene, @kids, $n) = ('', (), 2);
	$n = 2;
	for my $i (0 .. $#shapes) {
		push @kids, $n;
		$scene .= vchunk('nTRN', pack('V', $n) . vdict(_name => $shapes[$i][0]) . pack('VVVV', $n + 1, 0xffffffff, 0, 1) . vdict(_t => $shapes[$i][1]));
		$scene .= vchunk('nSHP', pack('V', $n + 1) . vdict() . pack('VV', 1, $i) . vdict());
		$n += 2;
	}
	my $rootn = vchunk('nTRN', pack('V', 0) . vdict(_name => $m->{name}) . pack('VVVV', 1, 0xffffffff, 0, 1) . vdict());
	my $grp = vchunk('nGRP', pack('V', 1) . vdict() . pack('V', scalar @kids) . pack('V*', @kids));
	my $layer = vchunk('LAYR', pack('V', 0) . vdict(_name => $m->{name}) . pack('V', 0xffffffff));
	my $rgba = '';
	for my $i (0 .. 255) {
		my $c = $m->{colors}[$i];
		$rgba .= $c ? pack('CCCC', @$c[ 1 .. 3 ], 255) : pack('CCCC', 0, 0, 0, 255);
	}
	my $matl = '';
	for my $i (0 .. $#{ $m->{colors} }) {
		next unless $m->{glow}{ $m->{colors}[$i][0] };
		$matl .= vchunk('MATL', pack('V', $i + 1) . vdict(_type => '_emit', _emit => '0.6', _flux => '1', _ldr => '0'));
	}
	die "$m->{name}: more than 255 colours\n" if @{ $m->{colors} } > 255;
	open my $fh, '>:raw', $path or die "$path: $!";
	print $fh 'VOX ' . pack('V', 200) . vchunk('MAIN', '', $body . $rootn . $grp . $scene . $layer . vchunk('RGBA', $rgba) . $matl);
	close $fh;
}

# ---------------------------------------------------------------- box data

sub write_data {
	my ($m, $path) = @_;
	my $by = VoxOut::parts_of($m);
	my $o = "-- Generated by assets/voxel-decor/source/build.pl from designs/. Cell frame in\n";
	$o .= "-- voxels of 0.25 studs: +X right, +Y up, front +Z, voxel i spans [i, i+1).\n";
	$o .= "-- box = x,y,z (min voxel), w,h,d, colour index.\n";
	$o .= "return {\n\tname = \"$m->{name}\",\n\tvoxel = 0.25,\n\tcolors = {\n";
	for (@{ $m->{colors} }) { $o .= sprintf "\t\t{ %d, %d, %d, %s },\n", @$_[ 1 .. 3 ], $m->{glow}{ $_->[0] } ? 'true' : 'false' }
	$o .= "\t},\n\tparts = {\n";
	my $total = 0;
	for my $name (@{ $m->{parts} }) {
		my $b = VoxOut::boxes_of($by->{$name} || []);
		next unless @$b;
		$total += @$b;
		$o .= sprintf "\t\t{ name = \"%s\", boxes = \"%s\" },\n", $name, join(';', map { join ',', @$_ } @$b);
	}
	$o .= "\t},\n}\n";
	open my $fh, '>', $path or die "$path: $!"; print $fh $o; close $fh;
	return $total;
}

# ---------------------------------------------------------------- previews

my $PI = 3.14159265;
sub view { my ($m, $yawDeg, $pitchDeg, $scale) = @_; return VoxOut::render_view($m, $yawDeg * $PI / 180, $pitchDeg * $PI / 180, $scale, 'color') }

sub compose {
	my ($views, $cols, $cellW, $cellH, $bg) = @_;
	my $rows = int((@$views + $cols - 1) / $cols);
	my ($W, $H) = ($cols * $cellW, $rows * $cellH);
	my @px = ($bg) x ($W * $H);
	for my $i (0 .. $#$views) {
		my $v = $views->[$i];
		my $ox = ($i % $cols) * $cellW + int(($cellW - $v->{w}) / 2);
		my $oy = int($i / $cols) * $cellH + ($cellH - $v->{h}) - 4;
		for my $y (0 .. $v->{h} - 1) {
			next if $oy + $y < 0;
			for my $x (0 .. $v->{w} - 1) {
				next if $ox + $x < 0 || $ox + $x >= $W;
				my $c = $v->{px}[ $y * $v->{w} + $x ];
				next if $c == $v->{bg};
				$px[ ($oy + $y) * $W + $ox + $x ] = $c;
			}
		}
	}
	VoxOut::png($_[5], $W, $H, \@px);
}

# ---------------------------------------------------------------- shapes

sub num { my $n = sprintf('%.3f', shift); $n =~ s/\.?0+$//; $n = '0' if $n eq '-0'; return $n }
sub luavec { return '{ ' . join(', ', map { num($_) } @_) . ' }' }

sub write_shapes {
	my ($path) = @_;
	my $o = "--[[\n\tDecorShapes - generated by assets/voxel-decor/source/build.pl. Do not edit.\n\n";
	$o .= "\tWhat each decor piece's .vox model needs from code, in studs, in its cell's\n";
	$o .= "\tframe (origin = middle of the cell floor, front +Z):\n\n";
	$o .= "\t  cells    footprint in grid cells (x, y, z), from the placed cell to +X\n";
	$o .= "\t           (right), +Y (up) and -Z (back)\n";
	$o .= "\t  size     the footprint in studs: a multiple of 4 on every axis\n";
	$o .= "\t  surface  height of a top something can stand on, when below a full cell\n";
	$o .= "\t  collide  \"none\" when the model is not solid (rungs carry the collision)\n";
	$o .= "\t  hinge    a door's hinge line (its Leaf turns about +Y through here)\n";
	$o .= "\t  seat     where to put the (invisible) Seat, and its size\n";
	$o .= "\t  flames   flame emitters: position, height, light range (nil = no light)\n";
	$o .= "\t  glows    flameless lights: position, range, colour\n";
	$o .= "\t  rungs    solid invisible boxes (centre, size), e.g. a ladder's rungs\n]]\n\nreturn {\n";
	for my $m (@all) {
		my $c = $m->{meta};
		my @cells = @{ $c->{cells} };
		$o .= "\t$m->{name} = {\n\t\tcells = " . luavec(@cells) . ",\n\t\tsize = " . luavec(map { $_ * 4 } @cells) . ",\n";
		$o .= "\t\tsurface = " . num($c->{surface}) . ",\n" if defined $c->{surface};
		$o .= "\t\tcollide = \"$c->{collide}\",\n" if $c->{collide};
		$o .= "\t\thinge = " . luavec(@{ $c->{hinge} }) . ",\n" if $c->{hinge};
		$o .= "\t\tseat = { at = " . luavec(@{ $c->{seat}{at} }) . ", size = " . luavec(@{ $c->{seat}{size} }) . " },\n" if $c->{seat};
		if (@{ $c->{flames} }) {
			$o .= "\t\tflames = {\n";
			$o .= "\t\t\t{ at = " . luavec(@{ $_->{at} }) . ", size = " . num($_->{size}) . (defined $_->{range} ? ", range = " . num($_->{range}) : '') . " },\n" for @{ $c->{flames} };
			$o .= "\t\t},\n";
		}
		if (@{ $c->{glows} }) {
			$o .= "\t\tglows = {\n";
			$o .= "\t\t\t{ at = " . luavec(@{ $_->{at} }) . ", range = " . num($_->{range}) . ", color = " . luavec(@{ $_->{color} }) . " },\n" for @{ $c->{glows} };
			$o .= "\t\t},\n";
		}
		if (@{ $c->{rungs} }) {
			$o .= "\t\trungs = {\n";
			$o .= "\t\t\t" . luavec(@$_) . ",\n" for @{ $c->{rungs} };
			$o .= "\t\t},\n";
		}
		$o .= "\t},\n";
	}
	$o .= "}\n";
	open my $fh, '>', $path or die "$path: $!"; print $fh $o; close $fh;
}

# ---------------------------------------------------------------- run

# Every piece must sit inside its footprint (cells(w, h, d) in the design,
# 1x1x1 by default): x from -8 to 16w-9, y from 0 to 16h-1, z from 7 back to
# 8-16d. Its footprint is what the game reserves, so a model poking out of it
# would overlap a neighbouring block. Also reports how much of the footprint
# the model spans, so an undersized piece is easy to spot.
my @bad;
for my $m (@all) {
	my ($w, $h, $d) = @{ $m->{meta}{cells} };
	my ($lo, $hi) = VoxOut::bounds([ map { [ split /,/ ] } keys %{ $m->{grid} } ]);
	my @min = (-8, 0, 8 - 16 * $d);
	my @max = (16 * $w - 9, 16 * $h - 1, 7);
	my @out = grep { $lo->[$_] < $min[$_] || $hi->[$_] > $max[$_] } 0 .. 2;
	push @bad, sprintf('%s spans x %d..%d y %d..%d z %d..%d, footprint x %d..%d y %d..%d z %d..%d',
		$m->{name}, $lo->[0], $hi->[0], $lo->[1], $hi->[1], $lo->[2], $hi->[2], $min[0], $max[0], $min[1], $max[1], $min[2], $max[2]) if @out;
	$m->{fill} = [ map { ($hi->[$_] - $lo->[$_] + 1) / ($max[$_] - $min[$_] + 1) } 0 .. 2 ];
}
die "Outside their footprint:\n  " . join("\n  ", @bad) . "\n" if @bad;

my @sheet;
for my $m (@built) {
	my $id = $m->{name};
	write_vox($m, "$root/vox/$id.vox");
	my $boxes = write_data($m, "$root/roblox/data/$id.lua");
	my $front = view($m, 215, 22, 6);
	my $back = view($m, 35, 22, 6);
	compose([ $front, $back ], 2, $front->{w} > $back->{w} ? $front->{w} : $back->{w}, $front->{h} > $back->{h} ? $front->{h} : $back->{h}, [ 52, 58, 70 ], "$root/previews/$id.png");
	push @sheet, view($m, 215, 22, 3);
	printf "%-18s %-6s fill %3d%% %3d%% %3d%%  %5d voxels %4d boxes %2d colours\n", $id, join('x', @{ $m->{meta}{cells} }),
		(map { $_ * 100 } @{ $m->{fill} }), scalar(keys %{ $m->{grid} }), $boxes, scalar @{ $m->{colors} };
}
if (!%want) {
	compose(\@sheet, 8, 120, 210, [ 52, 58, 70 ], "$root/previews/_sheet.png");
	write_shapes("$repo/src/ReplicatedStorage/Shared/Building/DecorShapes.lua");
	print scalar(@all) . " pieces\n";
}
