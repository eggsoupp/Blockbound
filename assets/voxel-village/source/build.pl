#!/usr/bin/perl
# Builds every spawn-village asset in designs/*.pl:
#   ../vox/<Id>.vox             MagicaVoxel scene, one named object per part
#   ../roblox/data/<Id>.lua     greedy-merged boxes + rig joints, collision,
#                               lights and anchors for ../roblox/BuildVillage.lua
#   ../previews/<Id>.png        front 3/4, other front 3/4, back 3/4 (+ parts
#                               view for rigs)
#   ../previews/_sheet.png      every asset, front 3/4 (full run only)
# Usage: perl build.pl [Id ...]
use strict;
use warnings;
use FindBin;
use lib $FindBin::Bin;
use lib "$FindBin::Bin/../../voxel-decor/source";
use lib "$FindBin::Bin/../../voxel-enemies/source";
use POSIX qw(floor);
use VoxLib;
use VoxOut;
use DecorKit;
use VillageKit;

my $root = "$FindBin::Bin/..";
my $repo = "$root/../..";
my %want = map { $_ => 1 } @ARGV;
mkdir "$root/$_" for qw(vox roblox roblox/data previews);

DecorKit::load_textures("$repo/assets/item-icons/source/icons.txt");
require "$repo/assets/voxel-decor/source/materials.pl";
require "$FindBin::Bin/materials.pl";
for my $file (sort glob("$FindBin::Bin/designs/*.pl")) {
	do $file or die "$file: " . ($@ || $!);
}

my @all = DecorKit::pieces();
my @built = grep { !%want || $want{ $_->{name} } } @all;
die "no assets match @ARGV\n" unless @built;

# ---------------------------------------------------------------- .vox

sub vchunk { my ($id, $c, $k) = @_; $k //= ''; return $id . pack('VV', length $c, length $k) . $c . $k }
sub vstr { my $s = shift; return pack('V', length $s) . $s }
sub vdict { my %d = @_; my $o = pack('V', scalar keys %d); $o .= vstr($_) . vstr($d{$_}) for sort keys %d; return $o }

# Roblox axes (front -Z) -> MagicaVoxel (z up, front -y): (x, y, z) ->
# (-x, z, y), a proper rotation, so nothing is mirrored. Each part is its own
# object, placed by its translation, so the scene opens assembled.
sub write_vox {
	my ($m, $path) = @_;
	my $by = VoxOut::parts_of($m);
	my (@shapes, $body);
	$body = '';
	for my $name (@{ $m->{parts} }) {
		my @v = map { [ -$_->[0], $_->[2], $_->[1], $_->[3] ] } @{ $by->{$name} || [] };
		next unless @v;
		my ($lo, $hi) = VoxOut::bounds(\@v);
		my @size = map { $hi->[$_] - $lo->[$_] + 1 } 0 .. 2;
		die "$m->{name}.$name is larger than 256 voxels\n" if grep { $_ > 256 } @size;
		my $xyzi = pack('V', scalar @v);
		$xyzi .= pack('CCCC', $_->[0] - $lo->[0], $_->[1] - $lo->[1], $_->[2] - $lo->[2], $_->[3]) for @v;
		$body .= vchunk('SIZE', pack('VVV', @size)) . vchunk('XYZI', $xyzi);
		my @t = map { $lo->[$_] + floor($size[$_] / 2) } 0 .. 2;
		push @shapes, [ $name, "@t" ];
	}
	my ($scene, @kids) = ('');
	my $n = 2;
	for my $i (0 .. $#shapes) {
		push @kids, $n;
		$scene .= vchunk('nTRN', pack('V', $n) . vdict(_name => $shapes[$i][0]) . pack('VVVV', $n + 1, 0xffffffff, 0, 1) . vdict(_t => $shapes[$i][1]));
		$scene .= vchunk('nSHP', pack('V', $n + 1) . vdict() . pack('VV', 1, $i) . vdict());
		$n += 2;
	}
	my $rootn = vchunk('nTRN', pack('V', 0) . vdict(_name => $m->{name}) . pack('VVVV', 1, 0xffffffff, 0, 1) . vdict());
	my $grp = vchunk('nGRP', pack('V', 1) . vdict() . pack('V', scalar @kids) . pack('V*', @kids));
	my $layer = vchunk('LAYR', pack('V', 0) . vdict(_name => $m->{name}) . pack('V', 0xffffffff));
	my $rgba = '';
	for my $i (0 .. 255) {
		my $c = $m->{colors}[$i];
		$rgba .= $c ? pack('CCCC', @$c[ 1 .. 3 ], 255) : pack('CCCC', 0, 0, 0, 255);
	}
	my $matl = '';
	for my $i (0 .. $#{ $m->{colors} }) {
		next unless $m->{glow}{ $m->{colors}[$i][0] };
		$matl .= vchunk('MATL', pack('V', $i + 1) . vdict(_type => '_emit', _emit => '0.6', _flux => '1', _ldr => '0'));
	}
	die "$m->{name}: more than 255 colours\n" if @{ $m->{colors} } > 255;
	open my $fh, '>:raw', $path or die "$path: $!";
	print $fh 'VOX ' . pack('V', 200) . vchunk('MAIN', '', $body . $rootn . $grp . $scene . $layer . vchunk('RGBA', $rgba) . $matl);
	close $fh;
}

# ---------------------------------------------------------------- box data

sub num { my $n = sprintf('%.3f', shift); $n =~ s/\.?0+$//; $n = '0' if $n eq '-0' || $n eq ''; return $n }
sub luavec { return '{ ' . join(', ', map { num($_) } @_) . ' }' }

sub write_data {
	my ($m, $path) = @_;
	my $by = VoxOut::parts_of($m);
	my $x = $m->{extra};
	my $meta = $m->{meta};
	my $o = "-- Generated by assets/voxel-village/source/build.pl from designs/. Do not edit.\n";
	$o .= "-- Voxels of 0.25 studs: +X right, +Y up, front -Z, voxel i spans [i, i+1).\n";
	$o .= "-- box = x,y,z (min voxel), w,h,d, colour index. pivot is in voxels;\n";
	$o .= "-- lights and anchors are in studs.\n";
	$o .= "return {\n\tname = \"$m->{name}\",\n\tvoxel = 0.25,\n";
	my $rig = grep { defined $m->{joints}{$_}{parent} } @{ $m->{parts} };
	$o .= "\trig = " . ($rig ? 'true' : 'false') . ",\n";
	$o .= "\tcolors = {\n";
	for (@{ $m->{colors} }) { $o .= sprintf "\t\t{ %d, %d, %d, %s },\n", @$_[ 1 .. 3 ], $m->{glow}{ $_->[0] } ? 'true' : 'false' }
	$o .= "\t},\n\tparts = {\n";
	my $total = 0;
	for my $name (@{ $m->{parts} }) {
		my $b = VoxOut::boxes_of($by->{$name} || []);
		next unless @$b;
		$total += @$b;
		my $j = $m->{joints}{$name};
		my $col = $x->{collide}{$name} // 'box';
		my $neon = $x->{neon}{$name} ? 'true' : 'false';
		$o .= sprintf "\t\t{ name = \"%s\", parent = %s, pivot = %s, collide = \"%s\", neon = %s,\n\t\t\tboxes = \"%s\" },\n",
			$name, defined $j->{parent} ? "\"$j->{parent}\"" : 'nil', luavec(@{ $j->{pivot} }), $col, $neon,
			join(';', map { join ',', @$_ } @$b);
	}
	$o .= "\t},\n\tlights = {\n";
	for (@{ $meta->{glows} }) { $o .= "\t\t{ at = " . luavec(@{ $_->{at} }) . ", range = " . num($_->{range}) . ", color = " . luavec(@{ $_->{color} }) . " },\n" }
	$o .= "\t},\n\tflames = {\n";
	for (@{ $meta->{flames} }) { $o .= "\t\t{ at = " . luavec(@{ $_->{at} }) . ", size = " . num($_->{size}) . (defined $_->{range} ? ", range = " . num($_->{range}) : '') . " },\n" }
	$o .= "\t},\n\tanchors = {\n";
	for (@{ $x->{anchors} }) { $o .= "\t\t$_->[0] = " . luavec(@$_[ 1 .. 3 ]) . ",\n" }
	$o .= "\t},\n}\n";
	open my $fh, '>', $path or die "$path: $!"; print $fh $o; close $fh;
	return $total;
}

# ---------------------------------------------------------------- previews

my $PI = 3.14159265;
sub view { my ($m, $yawDeg, $pitchDeg, $scale, $mode) = @_; return VoxOut::render_view($m, $yawDeg * $PI / 180, $pitchDeg * $PI / 180, $scale, $mode // 'color') }

sub compose {
	my ($views, $cols, $cellW, $cellH, $bg, $path) = @_;
	my $rows = int((@$views + $cols - 1) / $cols);
	my ($W, $H) = ($cols * $cellW, $rows * $cellH);
	my @px = ($bg) x ($W * $H);
	for my $i (0 .. $#$views) {
		my $v = $views->[$i];
		my $ox = ($i % $cols) * $cellW + int(($cellW - $v->{w}) / 2);
		my $oy = int($i / $cols) * $cellH + ($cellH - $v->{h}) - 4;
		for my $y (0 .. $v->{h} - 1) {
			next if $oy + $y < 0;
			for my $x (0 .. $v->{w} - 1) {
				next if $ox + $x < 0 || $ox + $x >= $W;
				my $c = $v->{px}[ $y * $v->{w} + $x ];
				next if $c == $v->{bg};
				$px[ ($oy + $y) * $W + $ox + $x ] = $c;
			}
		}
	}
	VoxOut::png($path, $W, $H, \@px);
}

sub maxdim { my ($vs, $k) = @_; my $m = 0; for (@$vs) { $m = $_->{$k} if $_->{$k} > $m } return $m }

# ---------------------------------------------------------------- run

my @sheet;
for my $m (@built) {
	my $id = $m->{name};
	write_vox($m, "$root/vox/$id.vox");
	my $boxes = write_data($m, "$root/roblox/data/$id.lua");
	my ($lo, $hi) = VoxOut::bounds([ map { [ split /,/ ] } keys %{ $m->{grid} } ]);
	my $span = 0; $span = $hi->[$_] - $lo->[$_] > $span ? $hi->[$_] - $lo->[$_] : $span for 0 .. 2;
	my $scale = $span > 120 ? 3 : $span > 60 ? 5 : 8;
	my @v = (view($m, 35, 22, $scale), view($m, 325, 22, $scale), view($m, 200, 22, $scale));
	push @v, view($m, 35, 10, $scale, 'parts') if @{ $m->{parts} } > 2;
	compose(\@v, scalar @v, maxdim(\@v, 'w'), maxdim(\@v, 'h'), [ 52, 58, 70 ], "$root/previews/$id.png");
	push @sheet, view($m, 35, 22, $span > 120 ? 1.4 : $span > 60 ? 2.2 : 3.5);
	printf "%-16s %6d voxels %5d boxes %3d colours  %d parts  size %.1f x %.1f x %.1f studs\n", $id,
		scalar(keys %{ $m->{grid} }), $boxes, scalar @{ $m->{colors} }, scalar @{ $m->{parts} },
		map { ($hi->[$_] - $lo->[$_] + 1) * 0.25 } 0 .. 2;
}
if (!%want) {
	compose(\@sheet, 4, maxdim(\@sheet, 'w'), maxdim(\@sheet, 'h'), [ 52, 58, 70 ], "$root/previews/_sheet.png");
	print scalar(@all) . " assets\n";
}
