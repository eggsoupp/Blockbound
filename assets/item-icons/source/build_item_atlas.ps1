# Rebuilds atlas/item_icons_atlas.png and src/ReplicatedStorage/Shared/UI/ItemSprites.lua
# from the 16x16 RPG icon sheets in sheets/.
#   powershell -ExecutionPolicy Bypass -File assets/item-icons/source/build_item_atlas.ps1
#
# The list below is APPEND-ONLY: a sprite's place on the atlas is its index in
# the list, so adding a sprite at the end never moves an existing one, and the
# old atlas upload keeps drawing every item it already had until the new one is
# uploaded and its id swapped into Theme.ItemAtlas.
#
#   name, sheet (file in sheets/ without .png), column, row  (16 px cells)
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$root = Split-Path -Parent $here
$repo = Split-Path -Parent (Split-Path -Parent $root)

$sprites = @(
	@('bottle_empty',    'potions',  1, 0),
	@('potion_red',      'potions',  3, 4),
	@('potion_blue',     'potions', 11, 4),
	@('armor_leather',   'armours',  0, 0),
	@('armor_iron',      'armours',  0, 8),
	@('chest_scroll',    'chests',   5, 0),
	@('ingot_copper',    'cave',     1, 3),
	@('ingot_iron',      'cave',     2, 3),
	@('ingot_gold',      'cave',     3, 3),
	@('ingot_mythril',   'cave',     4, 3),
	@('crystal_void',    'cave',     0, 1),
	@('gem_essence',     'cave',     1, 1)
)

$CELL = 16      # source cell and sprite size
$PITCH = 20     # sprite + 2 px clear gutter on every side
$PAD = 2
$COLUMNS = 12   # 12 * 20 + 2 = 242, inside a 256 wide atlas

Add-Type -AssemblyName System.Drawing

$rows = [math]::Ceiling($sprites.Count / $COLUMNS)
$width = 256
$height = $rows * $PITCH + $PAD
$atlas = New-Object System.Drawing.Bitmap $width, $height, ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
$g = [System.Drawing.Graphics]::FromImage($atlas)
$g.Clear([System.Drawing.Color]::Transparent)
$g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::NearestNeighbor
$g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::Half
$g.CompositingMode = [System.Drawing.Drawing2D.CompositingMode]::SourceCopy

$sheets = @{}
$lines = New-Object System.Collections.Generic.List[string]
for ($i = 0; $i -lt $sprites.Count; $i++) {
	$name, $sheet, $col, $row = $sprites[$i]
	if (-not $sheets.ContainsKey($sheet)) {
		$sheets[$sheet] = [System.Drawing.Bitmap]::FromFile((Join-Path $root "sheets/$sheet.png"))
	}
	$x = $PAD + ($i % $COLUMNS) * $PITCH
	$y = $PAD + [math]::Floor($i / $COLUMNS) * $PITCH
	$from = New-Object System.Drawing.Rectangle ($col * $CELL), ($row * $CELL), $CELL, $CELL
	$to = New-Object System.Drawing.Rectangle $x, $y, $CELL, $CELL
	$g.DrawImage($sheets[$sheet], $to, $from, [System.Drawing.GraphicsUnit]::Pixel)
	$lines.Add(("`t`t{0} = {{ offset = Vector2.new({1}, {2}), size = Vector2.new({3}, {3}) }}," -f $name, $x, $y, $CELL))
}
$g.Dispose()
$atlas.Save((Join-Path $root 'atlas/item_icons_atlas.png'), [System.Drawing.Imaging.ImageFormat]::Png)

$lua = @"
--[[
	ItemSprites

	GENERATED by assets/item-icons/source/build_item_atlas.ps1 - do not edit by
	hand; change the generator's list and run it again. The atlas's asset id is
	not here: it is Theme.ItemAtlas, so regenerating never loses it.

	An item names one of these with ``sprite`` in ItemDefinitions, and
	Shared.UI.ItemThumbnails draws it off the atlas.

	  offset, size  where the sprite sits on the atlas, in texels
]]

return {
	AtlasSize = Vector2.new($width, $height),
	Sprites = {
$($lines -join "`n")
	},
}
"@
$out = Join-Path $repo 'src/ReplicatedStorage/Shared/UI/ItemSprites.lua'
[System.IO.File]::WriteAllText($out, ($lua -replace "`r`n", "`n") + "`n", (New-Object System.Text.UTF8Encoding $false))
"wrote $($sprites.Count) sprites, atlas ${width}x$height"
