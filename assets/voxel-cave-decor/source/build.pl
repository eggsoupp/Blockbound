#!/usr/bin/perl
# Builds every cave decoration in designs.pl:
#   ../vox/<Model>.vox          MagicaVoxel model, the whole piece (Icicle3 is
#                               the three-block icicle, 16 x 48 x 16 voxels)
#   ../roblox/data/<Block>.lua  greedy-merged boxes for ONE block of it, in
#                               that block's own frame (Icicle3_1 = bottom block)
#   ../previews/<Model>.png     front 3/4 and back 3/4
#   ../previews/_sheet.png      every model, a row per biome
# Usage: perl build.pl
use strict;
use warnings;
use FindBin;
use lib $FindBin::Bin;
use lib "$FindBin::Bin/../../voxel-decor/source";
use lib "$FindBin::Bin/../../voxel-enemies/source";
use POSIX qw(floor);
use VoxLib;
use VoxOut;
use DecorKit;
use CaveKit;

my $root = "$FindBin::Bin/..";
my $repo = "$root/../..";
mkdir "$root/$_" for qw(vox roblox roblox/data previews);
unlink glob("$root/roblox/data/*.lua");

DecorKit::load_textures("$repo/assets/item-icons/source/icons.txt");
require "$FindBin::Bin/../../voxel-decor/source/materials.pl";
require "$FindBin::Bin/designs.pl";

my @models = CaveKit::models();

# The block name of segment s (1 = bottom) of a piece `tall` blocks high.
# Must match CaveDecor.segmentName.
sub segment_name { my ($block, $tall, $s) = @_; return $tall == 1 ? $block : "${block}${tall}_$s" }

# ---------------------------------------------------------------- .vox

sub vchunk { my ($id, $c, $k) = @_; $k //= ''; return $id . pack('VV', length $c, length $k) . $c . $k }
sub vstr { my $s = shift; return pack('V', length $s) . $s }
sub vdict { my %d = @_; my $o = pack('V', scalar keys %d); $o .= vstr($_) . vstr($d{$_}) for sort keys %d; return $o }

# Cell frame (x right, y up, front +Z) -> MagicaVoxel (x, y, z up), front
# facing MagicaVoxel's front (-y), every coordinate >= 0.
sub write_vox {
	my ($m, $path) = @_;
	my $by = VoxOut::parts_of($m);
	my (@shapes, $body);
	$body = '';
	for my $name (@{ $m->{parts} }) {
		my @v = map { [ $_->[0] + 8, 7 - $_->[2], $_->[1], $_->[3] ] } @{ $by->{$name} || [] };
		next unless @v;
		my ($lo, $hi) = VoxOut::bounds(\@v);
		my @size = map { $hi->[$_] - $lo->[$_] + 1 } 0 .. 2;
		my $xyzi = pack('V', scalar @v);
		$xyzi .= pack('CCCC', $_->[0] - $lo->[0], $_->[1] - $lo->[1], $_->[2] - $lo->[2], $_->[3]) for @v;
		$body .= vchunk('SIZE', pack('VVV', @size)) . vchunk('XYZI', $xyzi);
		my @t = map { $lo->[$_] + floor($size[$_] / 2) - ($_ == 2 ? 0 : 8) } 0 .. 2;
		push @shapes, [ $name, "@t" ];
	}
	my ($scene, @kids, $n) = ('', (), 2);
	$n = 2;
	for my $i (0 .. $#shapes) {
		push @kids, $n;
		$scene .= vchunk('nTRN', pack('V', $n) . vdict(_name => $shapes[$i][0]) . pack('VVVV', $n + 1, 0xffffffff, 0, 1) . vdict(_t => $shapes[$i][1]));
		$scene .= vchunk('nSHP', pack('V', $n + 1) . vdict() . pack('VV', 1, $i) . vdict());
		$n += 2;
	}
	my $rootn = vchunk('nTRN', pack('V', 0) . vdict(_name => $m->{name}) . pack('VVVV', 1, 0xffffffff, 0, 1) . vdict());
	my $grp = vchunk('nGRP', pack('V', 1) . vdict() . pack('V', scalar @kids) . pack('V*', @kids));
	my $layer = vchunk('LAYR', pack('V', 0) . vdict(_name => $m->{name}) . pack('V', 0xffffffff));
	my $rgba = '';
	for my $i (0 .. 255) {
		my $c = $m->{colors}[$i];
		$rgba .= $c ? pack('CCCC', @$c[ 1 .. 3 ], 255) : pack('CCCC', 0, 0, 0, 255);
	}
	my $matl = '';
	for my $i (0 .. $#{ $m->{colors} }) {
		next unless $m->{glow}{ $m->{colors}[$i][0] };
		$matl .= vchunk('MATL', pack('V', $i + 1) . vdict(_type => '_emit', _emit => '0.6', _flux => '1', _ldr => '0'));
	}
	die "$m->{name}: more than 255 colours\n" if @{ $m->{colors} } > 255;
	open my $fh, '>:raw', $path or die "$path: $!";
	print $fh 'VOX ' . pack('V', 200) . vchunk('MAIN', '', $body . $rootn . $grp . $scene . $layer . vchunk('RGBA', $rgba) . $matl);
	close $fh;
}

# ---------------------------------------------------------------- box data

# One block of a model: the voxels of rows 16(s-1)..16s-1, moved down to 0..15.
sub write_segment {
	my ($info, $s, $path) = @_;
	my $m = $info->{m};
	my $name = segment_name($info->{block}, $info->{tall}, $s);
	my $y0 = 16 * ($s - 1);
	my %by;
	while (my ($k, $v) = each %{ $m->{grid} }) {
		my ($x, $y, $z) = split /,/, $k;
		next if $y < $y0 || $y > $y0 + 15;
		push @{ $by{ $v->[0] } }, [ $x, $y - $y0, $z, $v->[1] ];
	}
	my $o = "-- Generated by assets/voxel-cave-decor/source/build.pl. One block of the\n";
	$o .= "-- $info->{id} model, in that block's frame: voxels of 0.25 studs, x and z\n";
	$o .= "-- -8..7, y 0..15, +Y up. box = x,y,z (min voxel), w,h,d, colour index.\n";
	$o .= "return {\n\tname = \"$name\",\n\tmodel = \"$info->{id}\",\n\tsegment = $s,\n\ttall = $info->{tall},\n\tvoxel = 0.25,\n\tcolors = {\n";
	for (@{ $m->{colors} }) { $o .= sprintf "\t\t{ %d, %d, %d, %s },\n", @$_[ 1 .. 3 ], $m->{glow}{ $_->[0] } ? 'true' : 'false' }
	$o .= "\t},\n\tparts = {\n";
	my ($total, $voxels) = (0, 0);
	for my $part (@{ $m->{parts} }) {
		my $list = $by{$part} or next;
		my $b = VoxOut::boxes_of($list);
		next unless @$b;
		$total += @$b;
		$voxels += @$list;
		my $see = $info->{parts}{$part};
		$o .= sprintf "\t\t{ name = \"%s\",%s boxes = \"%s\" },\n", $part,
			defined $see ? " transparency = $see," : '', join(';', map { join ',', @$_ } @$b);
	}
	$o .= "\t},\n}\n";
	die "$name is empty\n" unless $voxels;
	open my $fh, '>', $path or die "$path: $!"; print $fh $o; close $fh;
	return ($name, $total, $voxels);
}

# ---------------------------------------------------------------- previews

my $PI = 3.14159265;
sub view { my ($m, $yawDeg, $pitchDeg, $scale) = @_; return VoxOut::render_view($m, $yawDeg * $PI / 180, $pitchDeg * $PI / 180, $scale, 'color') }

# Views in a grid, bottoms aligned (or tops, for hanging pieces).
sub compose {
	my ($views, $cols, $cellW, $cellH, $bg, $path) = @_;
	my $rows = int((@$views + $cols - 1) / $cols);
	my ($W, $H) = ($cols * $cellW, $rows * $cellH);
	my @px = ($bg) x ($W * $H);
	for my $i (0 .. $#$views) {
		my $v = $views->[$i] or next;
		my $ox = ($i % $cols) * $cellW + int(($cellW - $v->{w}) / 2);
		my $oy = int($i / $cols) * $cellH + ($v->{hang} ? 4 : ($cellH - $v->{h}) - 4);
		for my $y (0 .. $v->{h} - 1) {
			next if $oy + $y < 0 || $oy + $y >= $H;
			for my $x (0 .. $v->{w} - 1) {
				next if $ox + $x < 0 || $ox + $x >= $W;
				my $c = $v->{px}[ $y * $v->{w} + $x ];
				next if $c == $v->{bg};
				$px[ ($oy + $y) * $W + $ox + $x ] = $c;
			}
		}
	}
	VoxOut::png($path, $W, $H, \@px);
}

# ---------------------------------------------------------------- run

my (@sheet, %row, @biomes);
for my $info (@models) {
	my $m = $info->{m};
	my $id = $info->{id};
	write_vox($m, "$root/vox/$id.vox");
	my @segs;
	for my $s (1 .. $info->{tall}) {
		my ($name, $boxes, $voxels) = write_segment($info, $s, "$root/roblox/data/" . segment_name($info->{block}, $info->{tall}, $s) . ".lua");
		push @segs, "$name $boxes";
	}
	my $front = view($m, 215, 22, 6);
	my $back = view($m, 35, 22, 6);
	compose([ $front, $back ], 2, ($front->{w} > $back->{w} ? $front->{w} : $back->{w}) + 8, ($front->{h} > $back->{h} ? $front->{h} : $back->{h}) + 8, [ 52, 58, 70 ], "$root/previews/$id.png");
	my $small = view($m, 215, 22, 3);
	$small->{hang} = $info->{anchor} eq 'ceiling';
	push @biomes, $info->{biome} unless $row{ $info->{biome} };
	push @{ $row{ $info->{biome} } }, $small;
	printf "%-22s %-7s %-4s %5d voxels %2d colours  mirrored %3d  boxes: %s\n", $id, $info->{anchor}, $info->{sym},
		scalar(keys %{ $m->{grid} }), scalar @{ $m->{colors} }, $info->{mirrored}, join(', ', @segs);
}

my $cols = 0;
for (@biomes) { $cols = @{ $row{$_} } if @{ $row{$_} } > $cols }
for my $b (@biomes) {
	my @r = @{ $row{$b} };
	push @sheet, @r, (undef) x ($cols - @r);
}
compose(\@sheet, $cols, 90, 170, [ 52, 58, 70 ], "$root/previews/_sheet.png");
print scalar(@models) . " models\n";
